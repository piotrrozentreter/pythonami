# Short-circuit and/or with falsy empty containers and None.

print("=== and/or values ===")
print(1 and 2)
print(0 and 9)
print(0 or 5)
print(4 or 0)
print([] and 99)
print([1] and 99)
print("" or "fallback")
print("keep" or "fallback")
print(None or False or 7)
print(0 and 1 or 2)
print(1 and 0 or 3)

print("=== not ===")
print(not False)
print(not True)
print(not 0)
print(not 1)
print(not [])
print(not [0])
print(not "")
print(not "x")
print(not None)
