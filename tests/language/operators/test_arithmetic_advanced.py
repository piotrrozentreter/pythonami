# Advanced arithmetic: Python floor-div/mod for negatives, precedence, unary.

print("=== floor/mod negatives ===")
print((-7) // 3)
print((-7) % 3)
print(7 // (-3))
print(7 % (-3))
print((-7) // (-3))
print((-7) % (-3))
print((-1) // 2)
print((-1) % 2)
print(1 // 2)
print(1 % 2)

print("=== precedence ===")
print(2 + 3 * 4)
print((2 + 3) * 4)
print(10 - 3 - 2)
print(20 // 3 * 2)
print(-(3 + 4))
print(-(-5))

print("=== comparisons ===")
print(1 < 2)
print(2 <= 2)
print(3 > 2)
print(3 >= 3)
print(1 != 0)
print(1 == 1)
print(4 != 4)
print((-1) < 0)
print(0 >= 0)
